#!/usr/bin/env node
// Regenerates the Digital Twin's quick-question chip buttons in
// code.html / index.html from knowledge.json entries that declare a
// `chip` field. Used by the /sync-twin command — run directly via
// `node scripts/sync-twin-chips.js` for a manual resync.
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FILES = ['code.html', 'index.html'];
const START_MARKER = '<!-- TWIN-CHIPS:START (generated by /sync-twin from knowledge.json — do not hand-edit) -->';
const END_MARKER = '<!-- TWIN-CHIPS:END -->';

const knowledge = JSON.parse(fs.readFileSync(path.join(ROOT, 'knowledge.json'), 'utf8'));

const chipEntries = knowledge.entries.filter((e) => typeof e.chip === 'string' && e.chip.trim() !== '');

if (chipEntries.length === 0) {
  console.error('No knowledge.json entries declare a "chip" field — nothing to generate.');
  process.exit(2);
}

function escapeAttr(str) {
  return str.replace(/'/g, "\\'");
}

function escapeHtml(str) {
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

const buttonsHtml = chipEntries.map((entry) => `                <button
                  class="px-3 py-1.5 rounded-full bg-blush-soft hover:bg-blush border border-plum/10 text-xs font-medium text-plum transition-all shadow-xs hover:-translate-y-0.5"
                  onclick="handleTwinQuestion('${escapeAttr(entry.chip)}')">
                  ✦ ${escapeHtml(entry.chip)}
                </button>`).join('\n');

let changedAny = false;

FILES.forEach((file) => {
  const filePath = path.join(ROOT, file);
  if (!fs.existsSync(filePath)) return;

  const content = fs.readFileSync(filePath, 'utf8');
  const startIdx = content.indexOf(START_MARKER);
  const endIdx = content.indexOf(END_MARKER);

  if (startIdx === -1 || endIdx === -1) {
    console.error(`${file}: could not find TWIN-CHIPS markers — skipping.`);
    return;
  }

  const before = content.slice(0, startIdx + START_MARKER.length);
  const after = content.slice(endIdx);
  const updated = `${before}\n${buttonsHtml}\n                ${after}`;

  if (updated !== content) {
    fs.writeFileSync(filePath, updated);
    changedAny = true;
    console.log(`${file}: chips regenerated (${chipEntries.length} chips).`);
  } else {
    console.log(`${file}: chips already up to date.`);
  }
});

if (!changedAny) {
  console.log('No changes needed.');
}
